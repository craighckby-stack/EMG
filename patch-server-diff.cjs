const fs = require('fs');

let content = fs.readFileSync('server.ts', 'utf8');

// Add import
if (!content.includes("import { applyPatch } from 'diff';")) {
  content = content.replace("import { GoogleGenAI } from '@google/genai';", "import { GoogleGenAI } from '@google/genai';\nimport { applyPatch } from 'diff';");
}

// Replace response generation logic
const search = `      if (!optimized || optimized.length < 5) {
        throw new Error('AI Model returned an empty code block.');
      }`;

const replace = `      if (!optimized || optimized.length < 5) {
        throw new Error('AI Model returned an empty code block.');
      }

      const patchText = optimized;
      let finalCode = code;
      
      try {
        let formattedPatch = patchText;
        if (!formattedPatch.startsWith('--- ')) {
            formattedPatch = \`--- a/file\\n+++ b/file\\n\${formattedPatch}\`;
        }
        const patched = applyPatch(code, formattedPatch, { fuzzFactor: 2 });
        if (patched !== false) {
           finalCode = patched;
        } else {
           throw new Error("Diff failed to apply cleanly.");
        }
      } catch (err) {
        throw new Error("Failed to apply the patch generated by the model: " + err.message);
      }
      optimized = finalCode;
`;

content = content.replace(search, replace);
fs.writeFileSync('server.ts', content);
console.log('patched server.ts diff apply');
